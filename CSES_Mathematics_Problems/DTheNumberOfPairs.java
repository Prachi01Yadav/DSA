    static void solve() throws Exception {
        long c = fs.nextLong();
        long d = fs.nextLong();
        long x = fs.nextLong();
        long cnt = 0;
        
        for (long i = 1; i * i <= x; i++) {
            if (x % i == 0) {
                
                long g1 = i;
                long cc1 = (x / g1) + d;
                if (cc1 % c == 0) {
                    int k = distinctPrimes[(int) (cc1 / c)];
                    cnt += (1 << k);
                }

                long g2 = x / i;
                if (g1 != g2) {
                    long cc2 = (x / g2) + d; 
                    if (cc2 % c == 0) {
                        int k = distinctPrimes[(int) (cc2 / c)];
                        cnt += (1 << k);
                    }
                }
            }
        }
        out.append(cnt).append('\n');
    }

    static final int mx = 20000007;
    static int[] distinctPrimes = new int[mx];

    static void prime() {
        for (int j = 2; j <mx; j += 2) {
            distinctPrimes[j]++;
        }

        for (int i = 3; i < mx; i += 2) {
            if (distinctPrimes[i] == 0) {
                for (int j = i; j < mx; j += i) {
                    distinctPrimes[j]++;
                }
            }
        }
    }

